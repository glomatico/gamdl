"""GAMDL 3.x-style video suffixes, including index-free cnID matching."""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path
from unittest.mock import Mock

from gamdl import _native
from gamdl.download import DownloadResult, MediaDatabase, Tags
from gamdl.download.path_resolver import (
    _numbered_video_path,
    resolve_numbered_video_path,
)
from gamdl.media import MusicVideo, UploadedVideo
from gamdl.muxer import Muxer


class VideoPathResolverTests(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.directory = Path(tmp.name)
        self.base = self.directory / "Same Title.m4v"
        self.video = MusicVideo.from_id("6805195215", api=Mock())

    def _write(self, path: Path, *, media_id: int | None = None) -> Path:
        # Model the MP4 iTunes atoms with the actual native tag writer when
        # possible; a bad file should never falsely match any media ID.
        if media_id is None:
            path.write_bytes(b"not an MP4")
            return path
        from shutil import which

        if not which("ffmpeg"):
            self.skipTest("ffmpeg required for native video tag fixtures")
        import subprocess

        subprocess.run(
            [
                "ffmpeg",
                "-nostdin",
                "-v",
                "error",
                "-y",
                "-f",
                "lavfi",
                "-i",
                "testsrc2=size=32x32:rate=1:duration=1",
                "-c:v",
                "mpeg4",
                "-f",
                "mp4",
                str(path),
            ],
            check=True,
            capture_output=True,
        )
        Muxer().tag(path, tags=Tags(title_id=media_id))
        return path

    def test_free_path_and_gap_selection_and_large_numbers(self):
        self.assertEqual(resolve_numbered_video_path(self.base, self.video), self.base)
        self._write(self.base)
        self._write(self.directory / "Same Title 3.m4v")
        self._write(self.directory / "Same Title 10.m4v")
        self._write(self.directory / "Same Title 02.m4v")  # not generated by old GAMDL
        self._write(self.directory / "Same Title 1.m4v")
        self.assertEqual(
            resolve_numbered_video_path(self.base, self.video),
            self.directory / "Same Title 2.m4v",
        )
        self._write(self.directory / "Same Title 2.m4v")
        self.assertEqual(
            resolve_numbered_video_path(self.base, self.video),
            self.directory / "Same Title 4.m4v",
        )

    def test_native_tag_matching_without_database_including_large_cnid(self):
        self._write(self.base, media_id=12345)
        self._write(self.directory / "Same Title 3.m4v", media_id=6805195215)
        self.assertEqual(_native.read_mp4_title_id(str(self.base)), "12345")
        self.assertEqual(
            _native.read_mp4_title_id(str(self.directory / "Same Title 3.m4v")),
            "6805195215",
        )
        self.assertEqual(
            resolve_numbered_video_path(self.base, self.video),
            self.directory / "Same Title 3.m4v",
        )
        self.assertIsNone(_native.read_mp4_title_id(str(self.directory / "none.m4v")))

    def test_sqlite_index_identity_takes_precedence_over_unreadable_tags(self):
        db = MediaDatabase(self.directory / "index.sqlite3")
        self._write(self.base)
        video = UploadedVideo.from_id("1234567890", api=Mock())
        db.record(video, DownloadResult(video.id, self.base, "downloaded", 10, None))
        self.assertEqual(
            resolve_numbered_video_path(self.base, video, database=db), self.base
        )
        self.assertEqual(
            resolve_numbered_video_path(self.base, self.video, database=db),
            self.directory / "Same Title 2.m4v",
        )

    def test_unrecognized_existing_video_must_not_be_treated_as_same_id(self):
        self._write(self.base)
        self.assertIsNone(_native.read_mp4_title_id(str(self.base)))
        self.assertEqual(
            resolve_numbered_video_path(self.base, self.video),
            self.directory / "Same Title 2.m4v",
        )

    def test_long_unicode_base_stays_within_filesystem_limit(self):
        base = self.directory / ("é" * 125 + ".m4v")
        candidate = _numbered_video_path(base, 2)
        self.assertTrue(candidate.name.endswith(" 2.m4v"))
        self.assertLessEqual(len(candidate.name.encode("utf-8")), 255)
        candidate.write_bytes(b"occupied")
        self.assertEqual(resolve_numbered_video_path(base, self.video), base)
        base.write_bytes(b"occupied")
        self.assertEqual(
            resolve_numbered_video_path(base, self.video),
            _numbered_video_path(base, 3),
        )
